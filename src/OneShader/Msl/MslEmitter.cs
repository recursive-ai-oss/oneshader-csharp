using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using OneShader.Diagnostics;
using OneShader.IR;
using OneShader.Reflection;
using OneShader.Types;

namespace OneShader.Msl;

/// <summary>
/// Writes one entry point and everything it reaches as an MSL source file. Functions keep their structure; module-scope
/// variables, which MSL does not have, become locals of the entry function that every helper receives as a reference
/// parameter. Resources are entry-function arguments with indices assigned in declaration order per argument class.
/// </summary>
internal sealed partial class MslEmitter
{
    private const int MaxDepth = 64;

    // Bounds the number of block emissions per function so a malformed CFG cannot make the emitter loop or blow up.
    private const int MaxBlockEmissions = 200_000;

    private readonly IrModule _m;
    private readonly MslOptions _o;
    private readonly DiagnosticBag _d;
    private readonly MslNames _names = new();
    private readonly StringBuilder _typeText = new();
    private readonly StringBuilder _layoutChecks = new();
    private readonly StringBuilder _fnText = new();
    private StringBuilder _out;
    private int _indent;
    private bool _failed;
    private bool _enable16;
    private EntryPoint _ep = null!;
    private string _entryName = "";

    public MslEmitter(IrModule m, MslOptions o, DiagnosticBag d)
    {
        _m = m;
        _o = o;
        _d = d;
        _out = _fnText;
        _enable16 = m.LayoutOptions.Enable16BitTypes;
    }

    private static string Inv(int v) => v.ToString(CultureInfo.InvariantCulture);

    private static string Inv(long v) => v.ToString(CultureInfo.InvariantCulture);

    private static string Inv(ulong v) => v.ToString(CultureInfo.InvariantCulture);

    private void Fail(string code, string message, SourceSpan span = default)
    {
        _failed = true;
        _d.Error(code, message, span);
    }

    private void Unsupported(string what, SourceSpan span = default) => Fail(MslCodes.Unsupported, what, span);

    private void Malformed(string what, SourceSpan span = default) => Fail(MslCodes.MalformedIr, what, span);

    private void W(string line)
    {
        _out.Append(' ', _indent * 4).Append(line).Append('\n');
    }

    /// <summary>Runs <paramref name="body"/> with output redirected, one indent level deeper, and returns what it wrote.</summary>
    private string Capture(Action body)
    {
        var saved = _out;
        _out = new StringBuilder();
        _indent++;
        try
        {
            body();
            return _out.ToString();
        }
        finally
        {
            _indent--;
            _out = saved;
        }
    }

    private void Raw(string text) => _out.Append(text);

    // ---- driver ------------------------------------------------------------------------------------

    public string? Run(string entryName)
    {
        EntryPoint? ep = null;
        foreach (var e in _m.EntryPoints)
        {
            if (e.Function.Name == entryName)
            {
                ep = e;
                break;
            }
        }

        if (ep is null)
        {
            Fail(MslCodes.EntryPointNotFound, "The module has no entry point named '" + entryName + "'; check the name passed to the compiler.");
            return null;
        }

        _ep = ep;
        if (!CheckWideTypes())
        {
            return null;
        }

        _entryName = _names.ClaimExact(MslNames.EntryName(ep.Function.Name));
        if (!CollectReachable())
        {
            return null;
        }

        AssignBindings();
        foreach (var f in _order)
        {
            if (f != ep.Function)
            {
                EmitFunction(f, false);
            }
        }

        EmitEntryFunction();
        if (_failed)
        {
            return null;
        }

        var sb = new StringBuilder();
        sb.Append("// Generated by OneShader. Metal Shading Language 2.4 or newer.\n");
        sb.Append("#include <metal_stdlib>\n");
        sb.Append("using namespace metal;\n\n");
        sb.Append(_typeText);
        if (_layoutChecks.Length > 0)
        {
            sb.Append("#ifdef ONESHADER_CHECK_LAYOUT\n").Append(_layoutChecks).Append("#endif\n\n");
        }

        sb.Append(_fnText);
        return sb.ToString();
    }

    // Metal has no 64-bit float, no 64-bit integer vectors in buffers and only one 64-bit atomic. Found up front so the error names the
    // line of the first use rather than coming out of type printing.
    private bool CheckWideTypes()
    {
        var use = WideTypeUse.Scan(_m, _ep);
        var fallback = _ep.Function.Span;
        if ((use.Features & DeviceFeatures.Float64) != 0)
        {
            Unsupported("MSL has no 64-bit floating-point type. Use float, or compile this shader for SPIR-V only.", use.Float64Site.IsKnown ? use.Float64Site : fallback);
        }

        if (use.HasInt64Vector)
        {
            Unsupported("MSL output cannot store 64-bit integer vectors in buffers (Metal has no packed long vectors). Use scalars, or compile this shader for SPIR-V only.", use.Int64VectorSite.IsKnown ? use.Int64VectorSite : fallback);
        }

        if (use.HasInt64AtomicUnsupportedOnMetal)
        {
            Unsupported("Metal 2.4 supports 64-bit atomics only as unsigned InterlockedMax / InterlockedMin on a buffer without using the returned value. Use that form, 32-bit atomics, or compile this shader for SPIR-V only.",
                use.Int64AtomicUnsupportedOnMetalSite.IsKnown ? use.Int64AtomicUnsupportedOnMetalSite : fallback);
        }

        return !_failed;
    }

    // ---- reachability -------------------------------------------------------------------------------

    private readonly List<IrFunction> _order = [];
    private readonly Dictionary<IrFunction, List<GlobalVariable>> _needed = [];
    private readonly Dictionary<GlobalVariable, int> _globalOrder = [];
    private readonly Dictionary<GlobalVariable, string> _globalNames = [];

    private bool CollectReachable()
    {
        for (int i = 0; i < _m.Globals.Count; i++)
        {
            _globalOrder[_m.Globals[i]] = i;
        }

        // Post-order over the call graph so callees are emitted (and declared) before their callers.
        var state = new Dictionary<IrFunction, int>();
        var stack = new Stack<(IrFunction F, int Block, int Inst)>();
        stack.Push((_ep.Function, 0, 0));
        state[_ep.Function] = 1;
        var direct = new Dictionary<IrFunction, HashSet<GlobalVariable>>();
        var callees = new Dictionary<IrFunction, List<IrFunction>>();
        while (stack.Count > 0)
        {
            var (f, bi, ii) = stack.Pop();
            if (!direct.ContainsKey(f))
            {
                direct[f] = [];
                callees[f] = [];
            }

            bool descended = false;
            for (; bi < f.Blocks.Count && !descended; bi++, ii = 0)
            {
                var insts = f.Blocks[bi].Instructions;
                for (; ii < insts.Count; ii++)
                {
                    var inst = insts[ii];
                    foreach (var op in inst.Operands)
                    {
                        if (op is GlobalVariable g)
                        {
                            direct[f].Add(g);
                        }
                    }

                    if (inst.Callee is { } callee && !callees[f].Contains(callee))
                    {
                        callees[f].Add(callee);
                        if (state.TryGetValue(callee, out int s))
                        {
                            if (s == 1)
                            {
                                Unsupported("The function '" + callee.Name + "' calls itself; MSL does not allow recursion.", callee.Span);
                                return false;
                            }
                        }
                        else
                        {
                            state[callee] = 1;
                            stack.Push((f, bi, ii + 1));
                            stack.Push((callee, 0, 0));
                            descended = true;
                            break;
                        }
                    }
                }
            }

            if (!descended)
            {
                state[f] = 2;
                _order.Add(f);
            }
        }

        foreach (var f in _order)
        {
            var set = new HashSet<GlobalVariable>(direct[f]);
            foreach (var c in callees[f])
            {
                foreach (var g in _needed[c])
                {
                    set.Add(g);
                }
            }

            if (f == _ep.Function)
            {
                foreach (var g in _ep.Inputs)
                {
                    set.Add(g);
                }

                foreach (var g in _ep.Outputs)
                {
                    set.Add(g);
                }
            }

            var list = new List<GlobalVariable>(set);
            list.Sort((a, b) => OrderOf(a).CompareTo(OrderOf(b)));
            _needed[f] = list;
        }

        foreach (var g in _needed[_ep.Function])
        {
            string hint = g.Name ?? "g";
            string prefix = _ep.Function.Name + ".";
            if (g.GlobalKind is GlobalKind.Input or GlobalKind.Output && hint.StartsWith(prefix, StringComparison.Ordinal))
            {
                hint = hint[prefix.Length..];
            }

            _globalNames[g] = _names.Claim(_o.KeepNames ? hint : "g", "g");
        }

        return true;
    }

    private int OrderOf(GlobalVariable g) => _globalOrder.TryGetValue(g, out int i) ? i : int.MaxValue;

    // ---- naming ---------------------------------------------------------------------------------------

    private readonly Dictionary<IrValue, string> _valueNames = [];
    private int _anon;

    private string NameOf(IrValue v)
    {
        if (v is GlobalVariable g)
        {
            return _globalNames.TryGetValue(g, out var gn) ? gn : (_globalNames[g] = _names.Claim(g.Name ?? "g", "g"));
        }

        if (_valueNames.TryGetValue(v, out var n))
        {
            return n;
        }

        string hint = _o.KeepNames && !string.IsNullOrEmpty(v.Name) ? v.Name! : string.Empty;
        _anon++;
        n = hint.Length > 0 ? _names.Claim(hint, "v" + Inv(_anon)) : _names.ClaimExact("v" + Inv(_anon));
        _valueNames[v] = n;
        return n;
    }

    /// <summary>The expression for an SSA value: a literal for constants, the variable name otherwise.</summary>
    private string V(IrValue v)
    {
        switch (v)
        {
            case Constant c:
                return ConstExpr(c, 0);
            case GlobalVariable g:
                Malformed("The global '" + g.Name + "' is used as a value; loads must go through a pointer.", g.Span);
                return "0";
            default:
                return NameOf(v);
        }
    }
}
